import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
import {reviseBuiltRoute,selectionOnlyChange} from '../lib/route-edit.js';
const source=readFileSync(new URL('../app.js',import.meta.url),'utf8');
const functions=source.slice(source.indexOf('function routeBuildKey(){'),source.indexOf('function routeHaversineDistance('));
const badge=source.slice(source.indexOf('function updateSelectedBadge('),source.indexOf('function readRouteTrayCollapsed('));
const nodes=new Map();const $=id=>{if(!nodes.has(id))nodes.set(id,{value:id==='routeCount'?'25':'',textContent:'',disabled:false});return nodes.get(id)};
const state={routeMode:'driving',selected:new Set(['a','b']),leads:[{id:'a',lat:40,lng:-82},{id:'b',lat:41,lng:-82}],routeStops:[],map:null};
let finish;
const context=vm.createContext({state,$,window:{},console,openRoutePanel(){},isCoords:()=>true,alert(){},nearestNeighbor2Opt:x=>x,renderRouteStops(){},endNavigation(){},drawRoutePreview(){},reviseBuiltRoute,selectionOnlyChange,osrmProfile:x=>x,fetch:()=>new Promise(resolve=>{finish=()=>resolve({ok:true,json:async()=>({order:[1,2],geometry:{type:'LineString'},distance:100,duration:60})})}),updateRouteTraySummary(){},shouldExpandRouteTray:()=>false,liftMapChrome(){}});
vm.runInContext(functions+badge,context);
const building=context.optimizeAndDrawRoute();
state.selected.delete('a');context.updateSelectedBadge({expand:false});
finish();await building;
assert.deepEqual(state.routeStops.map(x=>x.id),['b']);
assert.equal(state.routeGeometry,null,'old road geometry must not be restored');
assert.equal($('routeTray').dataset.routeStale,'true');
assert.equal($('startRouteBtn').disabled,false);
assert.equal($('optimizeRouteBtn').textContent,'Re-optimize');
assert.match($('routeTrayNote').textContent,/Stop removed/);
console.log('Retap during optimization ignores the late response and preserves the edited route');
